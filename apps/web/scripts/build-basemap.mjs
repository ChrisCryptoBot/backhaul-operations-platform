/**
 * Builds src/lib/basemap/us-states.ts: the lower-48 state outlines for the radar's bundled basemap, from the public-domain Census shapes in the `us-atlas` package, thinned and rounded to
 * about a mile so the file is small. Run once (`node apps/web/scripts/build-basemap.mjs`) and commit the result: the desk itself never reads `us-atlas` and never fetches a tile.
 */
import { createRequire } from "node:module";
import { writeFileSync, readFileSync } from "node:fs";
import { fileURLToPath } from "node:url";
import path from "node:path";

const require = createRequire(import.meta.url);
const { feature } = require("topojson-client");
const topo = JSON.parse(readFileSync(require.resolve("us-atlas/states-10m.json"), "utf8"));
const states = feature(topo, topo.objects.states).features;

const SKIP = new Set(["Alaska", "Hawaii", "Puerto Rico", "American Samoa", "Guam", "Commonwealth of the Northern Mariana Islands", "United States Virgin Islands"]);
const TOLERANCE = 0.02; // degrees, about a mile and a half

function dist(p, a, b) {
  const dx = b[0] - a[0];
  const dy = b[1] - a[1];
  const len = dx * dx + dy * dy;
  const t = len === 0 ? 0 : Math.max(0, Math.min(1, ((p[0] - a[0]) * dx + (p[1] - a[1]) * dy) / len));
  return Math.hypot(p[0] - (a[0] + t * dx), p[1] - (a[1] + t * dy));
}

// Douglas-Peucker on one ring.
function simplify(points, tol) {
  if (points.length <= 3) return points;
  const keep = new Array(points.length).fill(false);
  keep[0] = keep[points.length - 1] = true;
  const stack = [[0, points.length - 1]];
  while (stack.length) {
    const [a, b] = stack.pop();
    let max = 0;
    let at = -1;
    for (let i = a + 1; i < b; i++) {
      const d = dist(points[i], points[a], points[b]);
      if (d > max) {
        max = d;
        at = i;
      }
    }
    if (max > tol && at > -1) {
      keep[at] = true;
      stack.push([a, at], [at, b]);
    }
  }
  return points.filter((_, i) => keep[i]);
}
const round = (n) => Math.round(n * 100) / 100;

const out = [];
for (const f of states) {
  if (SKIP.has(f.properties.name)) continue;
  const polys = f.geometry.type === "Polygon" ? [f.geometry.coordinates] : f.geometry.coordinates;
  const rings = [];
  for (const poly of polys) {
    const ring = simplify(poly[0], TOLERANCE).map(([x, y]) => [round(x), round(y)]);
    if (ring.length >= 4) rings.push(ring);
  }
  out.push({ name: f.properties.name, rings });
}

const here = path.dirname(fileURLToPath(import.meta.url));
const file = path.join(here, "..", "src", "lib", "basemap", "us-states.ts");
const body = JSON.stringify(out);
writeFileSync(
  file,
  "/** GENERATED by scripts/build-basemap.mjs from the public-domain Census shapes in us-atlas: lower-48 state outlines, thinned to about a mile. Do not edit; rerun the script. [longitude, latitude] rings. */\n" +
    "export const US_STATES: ReadonlyArray<{ name: string; rings: ReadonlyArray<ReadonlyArray<readonly [number, number]>> }> = " +
    body +
    ";\n"
);
console.log(out.length + " states, " + (body.length / 1024).toFixed(0) + " KB -> " + path.relative(process.cwd(), file));
