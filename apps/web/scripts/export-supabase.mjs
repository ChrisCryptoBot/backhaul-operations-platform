// Writes dispatch-desk/supabase/ from prisma/migrations: the desk's migrations in Supabase CLI naming, plus the files that go with them.
//
//   npm run db:export-supabase        (from dispatch-desk, after any new Prisma migration)
//
// Prisma stays the source of truth. The desk's own migrations are the folders from 20261028000000 on; the older folders are the retired backhaul app. The
// "retire legacy tables" migration is left out: it drops tables a fresh database does not have, so on a new project it fails. tests/supabase-folder.test.ts fails
// until this has been re-run, so the two cannot drift. Nothing here touches a database.
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..", "..", "..");
const prismaDir = path.join(root, "prisma", "migrations");
const outDir = path.join(root, "supabase");
const migDir = path.join(outDir, "migrations");

const FIRST_DESK = "20261028000000";
const RETIRE = "20261028010000_retire_legacy_dispatch_tables";
const EXTENSIONS_NAME = "20261027000000_extensions";

const folders = fs
  .readdirSync(prismaDir, { withFileTypes: true })
  .filter((d) => d.isDirectory() && /^\d{14}_/.test(d.name) && d.name.slice(0, 14) >= FIRST_DESK)
  .map((d) => d.name)
  .sort();
const skipped = folders.filter((f) => f === RETIRE);
const desk = folders.filter((f) => f !== RETIRE);

// The lockdown always sorts after the last desk migration (one second later), so a later migration never lands behind it.
const RLS_NAME = `${String(BigInt(desk[desk.length - 1].slice(0, 14)) + 1n)}_enable_rls`;

const header = (from) => `-- Generated from ${from} by apps/web/scripts/export-supabase.mjs. Do not edit here: change the Prisma migration and run npm run db:export-supabase.\n\n`;

const EXTENSIONS_SQL = `-- Preflight. The trigram indexes in 20261106100000_scale_indexes_terminals need pg_trgm.
create extension if not exists pg_trgm with schema public;
`;

const LOCKDOWN_SQL = `-- Row level security on for every table in public, with no policies.
-- Supabase publishes every public table through its REST API; with row security off, anyone holding the project's anon key could read loads, driver pay and customer rates.
-- With it on and no policies, that door is closed. The desk's own server connects through Prisma as the owning postgres role, which is not subject to it, so the desk is unaffected.
-- Idempotent. Run it again after applying any later migration (a new table starts with row security off).
do $$
declare r record;
begin
  for r in select tablename from pg_tables where schemaname = 'public' loop
    execute format('alter table public.%I enable row level security', r.tablename);
  end loop;
end $$;
`;

fs.rmSync(migDir, { recursive: true, force: true });
fs.mkdirSync(migDir, { recursive: true });

/** @type {Array<{ file: string; sql: string }>} */
const files = [{ file: `${EXTENSIONS_NAME}.sql`, sql: EXTENSIONS_SQL }];
for (const f of desk) files.push({ file: `${f}.sql`, sql: header(`prisma/migrations/${f}/migration.sql`) + fs.readFileSync(path.join(prismaDir, f, "migration.sql"), "utf8") });
files.push({ file: `${RLS_NAME}.sql`, sql: LOCKDOWN_SQL });
for (const { file, sql } of files) fs.writeFileSync(path.join(migDir, file), sql);

fs.writeFileSync(path.join(outDir, "lockdown_rls.sql"), LOCKDOWN_SQL);

// One file for the SQL editor. The editor runs a multi-statement script as a single transaction, so a failure leaves nothing half-applied.
const all = [`-- Every desk migration in order, for one paste into the Supabase SQL editor of the DESK's own project (never the phone's truelane-prod).\n-- ${files.length} parts: extensions, ${desk.length} desk migrations, row security lockdown. Generated by apps/web/scripts/export-supabase.mjs.\n`];
for (const { file, sql } of files) all.push(`\n-- =====================================================================================\n-- ${file}\n-- =====================================================================================\n${sql.endsWith("\n") ? sql : `${sql}\n`}`);
fs.writeFileSync(path.join(outDir, "apply-all.sql"), all.join(""));

// verify.sql: what each migration made, checked by the objects themselves. Tables and columns are read out of the migrations' own statements; later drops take them back out.
const tables = new Map(); // table -> migration
const columns = new Map(); // "table.column" -> { table, column, migration }
for (const f of desk) {
  const text = fs.readFileSync(path.join(prismaDir, f, "migration.sql"), "utf8").replace(/--.*$/gm, "");
  for (const m of text.matchAll(/CREATE TABLE\s+(?:IF NOT EXISTS\s+)?"([^"]+)"/gi)) tables.set(m[1], f);
  for (const m of text.matchAll(/DROP TABLE\s+(?:IF EXISTS\s+)?"([^"]+)"/gi)) {
    tables.delete(m[1]);
    for (const k of [...columns.keys()]) if (k.startsWith(`${m[1]}.`)) columns.delete(k);
  }
  for (const st of text.split(";")) {
    const alter = /ALTER TABLE\s+(?:ONLY\s+)?"([^"]+)"/i.exec(st);
    if (!alter) continue;
    for (const m of st.matchAll(/ADD COLUMN\s+(?:IF NOT EXISTS\s+)?"([^"]+)"/gi)) columns.set(`${alter[1]}.${m[1]}`, { table: alter[1], column: m[1], migration: f });
    for (const m of st.matchAll(/DROP COLUMN\s+(?:IF EXISTS\s+)?"([^"]+)"/gi)) columns.delete(`${alter[1]}.${m[1]}`);
  }
}
const want = [
  ...[...tables].map(([t, f]) => `('${f}','${t}',null::text)`),
  ...[...columns.values()].map((c) => `('${c.migration}','${c.table}','${c.column}')`)
].sort();
const verify = `-- Run in the SQL editor of the desk's database after applying. Every row of the first result should say present; the second should be 0; the third should be the same list of tables as 'select tablename from pg_tables where schemaname = ''public'''.
-- Generated by apps/web/scripts/export-supabase.mjs from the migrations' own statements (${tables.size} tables, ${columns.size} added columns).
with want(migration, tbl, col) as (values
${want.join(",\n")})
select w.migration, w.tbl, w.col,
       case when exists (select 1 from information_schema.columns c
                         where c.table_schema = 'public' and c.table_name = w.tbl and (w.col is null or c.column_name = w.col))
            then 'present' else 'MISSING' end as state
from want w
order by state desc, w.migration, w.tbl, w.col;

-- Tables in public with row level security still off (must be none after the lockdown file).
select tablename from pg_tables where schemaname = 'public' and not rowsecurity order by 1;

-- Every table in public.
select tablename, rowsecurity from pg_tables where schemaname = 'public' order by 1;
`;
fs.writeFileSync(path.join(outDir, "verify.sql"), verify);

// After applying by hand, tell Prisma the history is already in (so a later "prisma migrate deploy" does not try to run it again, or the retire migration at all).
const allFolders = [...skipped, ...desk].sort();
fs.writeFileSync(
  path.join(outDir, "mark-applied.sh"),
  `#!/usr/bin/env sh
# After applying the SQL by hand: record every desk migration in Prisma's own history so "prisma migrate deploy" has nothing left to run.
# Run from dispatch-desk with DATABASE_URL pointing at the desk's database (the direct connection, port 5432).
# ${RETIRE} is marked applied without being run: it is for a database that still has the old tables, and a fresh one never did.
set -e
for m in \\
${allFolders.map((f) => `  ${f}`).join(" \\\n")}; do
  npx prisma migrate resolve --applied "$m" --schema=./prisma/schema.prisma
done
`
);
fs.writeFileSync(
  path.join(outDir, "mark-applied.ps1"),
  `# After applying the SQL by hand: record every desk migration in Prisma's own history so "prisma migrate deploy" has nothing left to run.
# Run from dispatch-desk with $env:DATABASE_URL pointing at the desk's database (the direct connection, port 5432).
# ${RETIRE} is marked applied without being run: it is for a database that still has the old tables, and a fresh one never did.
$ErrorActionPreference = "Stop"
$migrations = @(
${allFolders.map((f) => `  "${f}"`).join(",\n")}
)
foreach ($m in $migrations) {
  npx prisma migrate resolve --applied $m --schema=./prisma/schema.prisma
}
`
);

console.log(`supabase/: ${files.length} migration files (${desk.length} desk migrations, 1 preflight, 1 lockdown), left out ${skipped.join(", ") || "nothing"}`);
