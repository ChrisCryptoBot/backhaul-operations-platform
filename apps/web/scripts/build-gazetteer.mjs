// Builds the desk's offline place data: src/lib/gazetteer/zips.ts (about 33,000 ZIP code centres) and places.ts (about 32,000 cities, towns and census places), from the US Census Gazetteer files
// (public domain). Dev-time only: the output is committed, so the desk and its tests never fetch anything.
//
//   curl -sSLO https://www2.census.gov/geo/docs/maps-data/data/gazetteer/2023_Gazetteer/2023_Gaz_zcta_national.zip
//   curl -sSLO https://www2.census.gov/geo/docs/maps-data/data/gazetteer/2023_Gazetteer/2023_Gaz_place_national.zip
//   (unzip both into one folder)
//   node apps/web/scripts/build-gazetteer.mjs <folder with the two .txt files>
//
// ZIPs are "ZIP,lat,lng" lines to three places (about 100 m). Places are "ST|Name|lat|lng|square miles|A or S" lines (A: an incorporated place, S: a census-designated place), with the
// Census's kind word ("city", "town", "CDP") taken off the name. The state centres in lib/gazetteer/states.ts are written by hand and are not touched here.
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const dir = process.argv[2];
if (!dir) {
  console.error("Usage: node apps/web/scripts/build-gazetteer.mjs <folder with 2023_Gaz_zcta_national.txt and 2023_Gaz_place_national.txt>");
  process.exit(1);
}
const out = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..", "src", "lib", "gazetteer");
fs.mkdirSync(out, { recursive: true });

const rows = (file) => {
  const lines = fs.readFileSync(path.join(dir, file), "utf8").split(/\r?\n/).filter((l) => l.trim() !== "");
  const head = lines[0].split("\t").map((h) => h.trim());
  return lines.slice(1).map((l) => {
    const cells = l.split("\t").map((c) => c.trim());
    return Object.fromEntries(head.map((h, i) => [h, cells[i]]));
  });
};
const n = (v, d) => Number(v).toFixed(d);

// Continental US, Alaska, Hawaii and the territories the Census lists; the radar draws the lower 48, but a ZIP anywhere should still resolve.
const zips = rows("2023_Gaz_zcta_national.txt")
  .filter((r) => /^\d{5}$/.test(r.GEOID) && Number.isFinite(Number(r.INTPTLAT)) && Number.isFinite(Number(r.INTPTLONG)))
  .sort((a, b) => (a.GEOID < b.GEOID ? -1 : 1))
  .map((r) => `${r.GEOID},${n(r.INTPTLAT, 3)},${n(r.INTPTLONG, 3)}`);

const KIND = /\s+(city and borough|consolidated government \(balance\)|metropolitan government \(balance\)|metro government \(balance\)|unified government \(balance\)|urban county|municipality|comunidad|zona urbana|borough|village|town|city|CDP)(\s+\(balance\))?$/i;
const strip = (name) => {
  let s = name;
  for (let i = 0; i < 3; i++) {
    const t = s.replace(KIND, "");
    if (t === s) break;
    s = t;
  }
  return s.trim();
};
const places = rows("2023_Gaz_place_national.txt")
  .filter((r) => /^[A-Z]{2}$/.test(r.USPS) && Number.isFinite(Number(r.INTPTLAT)) && Number.isFinite(Number(r.INTPTLONG)))
  .map((r) => `${r.USPS}|${strip(r.NAME).replaceAll("|", " ")}|${n(r.INTPTLAT, 3)}|${n(r.INTPTLONG, 3)}|${Math.round(Number(r.ALAND_SQMI) || 0)}|${r.FUNCSTAT === "A" ? "A" : "S"}`)
  .sort();

const head = (what) => `// Generated by apps/web/scripts/build-gazetteer.mjs from the US Census Gazetteer (public domain). Do not edit. SERVER ONLY: nothing in src/components may import this (tests/gazetteer.test.ts).\n// ${what}\n`;
fs.writeFileSync(path.join(out, "zips.ts"), `${head("One ZIP per line: ZIP,lat,lng.")}export const ZIP_LINES = ${JSON.stringify(zips.join("\n"))};\n`);
fs.writeFileSync(path.join(out, "places.ts"), `${head("One place per line: ST|Name|lat|lng|square miles|A (incorporated) or S (census-designated).")}export const PLACE_LINES = ${JSON.stringify(places.join("\n"))};\n`);
console.log(`gazetteer: ${zips.length} ZIPs, ${places.length} places`);
